export async function seedJobTitles(): Promise<void> {
  try {
    const [result] = await db.select({ value: count() }).from(corporateJobTitles);
    
    if (result && result.value > 0) {
      console.log(`[Job Titles Seed] Skipping - ${result.value} job titles already exist`);
      return;
    }

    console.log("[Job Titles Seed] Seeding predefined job titles...");

    const seedData = PREDEFINED_JOB_TITLES.map((title) => ({
      organizationId: null,
      title: title.title,
      description: title.description,
      departmentCategory: title.departmentCategory,
      industrySpecialization: title.industrySpecialization,
      assignedRoles: title.assignedRoles,
      primaryRole: title.primaryRole,
      additionalPermissions: [] as string[],
      restrictedPermissions: [] as string[],
      hierarchyLevel: title.hierarchyLevel,
      reportsToTitleId: null,
      displayOrder: title.displayOrder,
      isActive: true,
      isSystemTemplate: true,
      createdBy: null,
    }));

    await db.insert(corporateJobTitles).values(seedData);

    console.log(`[Job Titles Seed] Successfully seeded ${PREDEFINED_JOB_TITLES.length} job titles`);
  } catch (error) {
    console.error("[Job Titles Seed] Error seeding job titles:", error);
    throw error;
  }
}

